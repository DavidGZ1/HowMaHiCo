getwd()
folder = file.path("2_data")

# functions
get_annot_fp <- function(file_list, folder){
  # read fragipe psm, get source files and directory (Sample_fp)
  output_list <- sapply(file_list, USE.NAMES = TRUE, simplify = FALSE, function(x){
    input <- paste0(folder, "/", x)
    read_tsv(input, col_select = "Spectrum", show_col_types = FALSE) %>% 
      mutate(Source_file = sub("[.].*", "", Spectrum)) %>% 
      pull(Source_file) %>% 
      unique()
  })
  stack(output_list) %>% 
    rename(Source_file = values, Sample_fp = ind) %>% 
    mutate(Sample_fp = gsub("/psm.tsv", "", Sample_fp, fixed = TRUE)) %>% 
    mutate(Source_file = gsub("_diatracer", "", Source_file, fixed = TRUE)) %>% 
    mutate(Condition = "", BioReplicate = "", TechReplicate = "", Sample = "", Sample_ID = "")  %>% 
    arrange(Source_file)
}
get_annot_diann <- function(file_list, folder){
  # read fragipe-diann report, get source files and directory (Sample_fp)
  output_list <- sapply(file_list, USE.NAMES = TRUE, simplify = FALSE, function(x){
    input <- paste0(folder, "/", x)
    read_tsv(input,  col_select = "Run", show_col_types = FALSE) %>%  
      rename(Source_file = Run) %>% 
      pull(Source_file) %>% 
      unique()
  })
  stack(output_list) %>% 
    rename(Source_file = values, Sample_fp = ind) %>% 
    mutate(Sample_fp = gsub("/report.tsv", "", Sample_fp, fixed = TRUE))  %>% 
    mutate(Condition = "", BioReplicate = "", TechReplicate = "", Sample = "", Sample_ID = "")  %>% 
    arrange(Source_file)
}


# # get index of files in the folder
data_files <- list.files(folder, recursive = TRUE)
psm_files <- data_files[grepl("psm.tsv", data_files)]
diann_files <- data_files[grepl("report.tsv", data_files)]

annot_auto_psm <- get_annot_fp(file_list = psm_files, folder = folder)
write.csv(annot_auto_psm, row.names = FALSE,
          file = file.path("1_documentation", "sample_annotation_autogenerated_psm.csv"))

annot_auto_diann <- get_annot_diann(file_list = diann_files, folder = folder)


write.csv(annot_auto_diann, row.names = FALSE,
          file = file.path("1_documentation", "sample_annotation_autogenerated_diann.csv"))



